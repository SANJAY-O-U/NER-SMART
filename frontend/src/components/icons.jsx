/**
 * Minimal inline stroke icons (24x24 viewBox). Inline SVG keeps the bundle free of an icon
 * dependency. Icons are decorative: they are hidden from assistive tech and every control that
 * uses one also carries a text label or an aria-label.
 */
function Icon({ children, className = "h-5 w-5", ...rest }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
      {...rest}
    >
      {children}
    </svg>
  );
}

